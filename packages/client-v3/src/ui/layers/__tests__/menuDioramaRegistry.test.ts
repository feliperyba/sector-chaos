      expect(bg.hazeColor).toBe(EXPECTED_HAZE[id]); // same tint on both layers
      expect(mid.hazeAlpha).toBeUndefined(); // nearest plane — no haze
      expect(fg.hazeAlpha).toBeUndefined();
