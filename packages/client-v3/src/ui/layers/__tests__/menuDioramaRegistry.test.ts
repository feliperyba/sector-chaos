  it('the 8 variants use distinct terrain base floors (distinct scene vocabularies)', () => {
    // Pin that each variant reads as a DIFFERENT scene — not 8 reshuffles of
    // the same floor. Extract the dominant BG frame per variant (the base
    // floor). Two variants MAY share a base (crypt/flooded/secret-passage all
    // use tiles_cracked) but must differ in vocabulary — so we additionally
    // require the full tile-set signature to be unique per variant.
    const signatures = new Map<string, Set<string>>();
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const composition = getMenuDioramaComposition(id);
      const frames = new Set<string>();
      for (const layer of composition) for (const t of layer.tiles) frames.add(t.frame);
      // Each variant's full frame-set signature must be unique.
      expect(signatures.has(id)).toBe(false);
      signatures.set(id, frames);
    }
    const sigJsons = new Set<string>();
    for (const [id, frames] of signatures) {
      const sig = JSON.stringify([...frames].sort());
      // A signature colliding with another variant would mean two variants
      // use the identical frame vocabulary — i.e. a reshuffle, not a distinct
      // scene. All 8 must differ.
      expect(sigJsons.has(sig)).toBe(false);
      sigJsons.add(sig);
    }
  });
