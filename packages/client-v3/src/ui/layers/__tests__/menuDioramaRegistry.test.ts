// ─── Biome crystal placements (per-variant rig — redesign-tuned) ─────────────
//
// The menu redesign (67f3626 + 347a748) retuned the biome-glow crystals per
// variant instead of the ticket-15 constant "exactly 2 per variant": some rigs
// DROP their crystals (the fire is the sole hero), some are crystal-dominant
