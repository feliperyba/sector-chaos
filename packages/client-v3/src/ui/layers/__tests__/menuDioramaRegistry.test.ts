// crystal-bearing variants are DISTINCT. These tests pin the shipped rig.

describe('biome crystal placements — per-variant rig (redesign-tuned)', () => {
  it('every variant ships its EXPECTED_CRYSTALS rig — exact count, one hue per variant', () => {
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const expected = EXPECTED_CRYSTALS[id];
      if (!expected) throw new Error(`missing EXPECTED_CRYSTALS entry for ${id}`);
      const crystals = getMenuDioramaPlacements(id).filter((p) => p.kind === 'biome-glow');
      expect(crystals, `${id}: expected ${expected.count} crystals`).toHaveLength(expected.count);
      for (const c of crystals) {
        expect(c.color).toEqual(expected.hue);
      }
    }
  });

  it('every crystal stays OFF the button UI stage (cols 6–9, rows 4–6)', () => {
    // The menu buttons render over cols 6–9, rows 4–6 — the redesign kept every
    // crystal clear of that zone (crystal pools read as atmosphere, never as
    // glare behind the buttons).
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const crystals = getMenuDioramaPlacements(id).filter((p) => p.kind === 'biome-glow');
      const intruders = crystals.filter(
        (c) => c.gridX >= 6 && c.gridX <= 9 && c.gridY >= 4 && c.gridY <= 6,
      );
      expect(intruders, `${id}: crystal sits behind the menu buttons`).toEqual([]);
    }
  });

  it('the crystal hues are DISTINCT (each crystal-bearing variant its own flavour — not generic blue)', () => {
    // NO two crystal-bearing variants share a crystal hue, and NONE is the
    // shipped biome-glow blue [0.4, 0.68, 1.0]. Rounded so float noise can't
    // fake a distinction.
    const SHIPPED_BLUE = [0.4, 0.68, 1.0] as const;
    const blueSig = SHIPPED_BLUE.map((c: number) => Number(c.toFixed(3))).join(',');
    const hues = new Set<string>();
    let crystalBearing = 0;
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const hue = EXPECTED_CRYSTALS[id]!.hue;
      if (!hue) continue; // crystal-free rig — nothing to pin here
      crystalBearing++;
      const sig = hue.map((c: number) => Number(c.toFixed(3))).join(',');
      expect(sig, `${id}: crystal hue must not be the shipped biome-glow blue`).not.toBe(blueSig);
      expect(hues.has(sig), `${id}: crystal hue collides with another variant`).toBe(false);
      hues.add(sig);
    }
    expect(hues.size).toBe(crystalBearing);
  });

  it('every crystal hue is the 2nd tone — distinct from every warm-fire palette color (2-tone contract)', () => {
    // Tone 1 (the fire key + perimeter rig) is warm; the crystal hue is
    // tone 2. Pin that no variant's crystal hue collapses onto a warm-fire palette
    // color (which would erase the 2-tone separation the redesign shipped).
    const WARM = new Set(
      [
        LIGHT_PALETTE.campfire.color,
        LIGHT_PALETTE.brazier.color,
        LIGHT_PALETTE.torch.color,
        LIGHT_PALETTE.aura.color,
      ].map((c: readonly [number, number, number]) =>
        c.map((v: number) => Number(v.toFixed(2))).join(','),
      ),
    );
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const hue = EXPECTED_CRYSTALS[id]!.hue;
      if (!hue) continue; // crystal-free rig — nothing to pin here
      const sig = hue.map((c: number) => Number(c.toFixed(2))).join(',');
      expect(WARM.has(sig), `${id}: crystal hue is byte-identical to a warm-fire color`).toBe(false);
    }
  });
});

