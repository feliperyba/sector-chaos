// ─── Map grammar contract (Bomberman structure applied to EVERY variant) ────
//
// These assertions pin the load-bearing invariants of the cinematic diorama
// design (boardroom session 1 — layered hierarchy + per-variant geometry):
//   - Floor underlay covers the full 16×9 grid with opaque tiles (no-black).
//   - Border ring with rotated side walls + 4 oriented corners (the arena frame).
//   - 2×2 hearth centered on the fire anchor (the focal pedestal).
//   - Scatter is bounded (3–14 props) — rich but never cluttered.
//   - The fire focal zone stays clear of scatter props.
//   - The button UI stage stays free of tall props (readability).
//   - Lighting is a composed rig (3–5 fixtures — the harmony budget).
//   - No light fixture stacks on a cover/loot prop (the regression guard).
//   - Each variant has a distinct frame-set vocabulary (8 different places).

describe('diorama composition contract — cinematic hierarchy applied to all 7 variants', () => {
  it('(M1) every BG layer covers the full 16×9 grid (no-black invariant)', () => {
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const bg = getMenuDioramaComposition(id).find((l) => l.id === 'bg')!;
      const cells = new Set(bg.tiles.map((t) => `${t.col},${t.row}`));
      for (let col = 0; col < 16; col++) {
        for (let row = 0; row < 9; row++) {
          expect(cells.has(`${col},${row}`)).toBe(true);
        }
      }
    }
  });

  it('(M2) every MID has a border ring with rotated side walls + 4 oriented corners', () => {
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const mid = getMenuDioramaComposition(id).find((l) => l.id === 'mid')!;
      // Left border walls rotated 90°, right border walls rotated 270°
      for (const row of [1, 2, 3, 4, 5, 6, 7]) {
        const left = mid.tiles.find((t) => t.col === 0 && t.row === row);
        expect(left).toBeDefined();
        expect(left!.rotation).toBe(90);
        const right = mid.tiles.find((t) => t.col === 15 && t.row === row);
        expect(right).toBeDefined();
        expect(right!.rotation).toBe(270);
      }
      // 4 wall_corners with rotations {0, 90, 180, 270}
      const corners = mid.tiles.filter((t) => t.frame === 'wall_corner');
      expect(corners).toHaveLength(4);
      const rotations = new Set(corners.map((t) => t.rotation ?? 0));
      for (const expected of [0, 90, 180, 270]) {
        expect(rotations.has(expected)).toBe(true);
      }
    }
  });

  it('(M6) every MID has a 2×2 hearth centered on (7.5, 1.5)', () => {
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const mid = getMenuDioramaComposition(id).find((l) => l.id === 'mid')!;
      const HEARTH_FRAMES = new Set(['tile', 'tiles_center']);
      const hearth = mid.tiles.filter((t) => HEARTH_FRAMES.has(t.frame));
      expect(hearth.length).toBeGreaterThanOrEqual(4);
      for (const [c, r] of [[7, 1], [8, 1], [7, 2], [8, 2]]) {
        expect(hearth.some((t) => t.col === c && t.row === r)).toBe(true);
      }
    }
  });

  it('every MID scatter is bounded — rich but never cluttered (3–14 props)', () => {
    // Anti-clutter + anti-emptiness guard. The wall ring (50 tiles) + hearth (4)
    // are the shared base; scatter is the variant's own composed props. Cap at
    // 14 so a future edit can't regress to the wallpaper-every-corner layout;
    // floor at 3 so it can't regress to an empty stage either.
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const mid = getMenuDioramaComposition(id).find((l) => l.id === 'mid')!;
      // Border ring is always 50 tiles (16+16+7+7+4) + hearth 4 = 54 base.
      const scatterApprox = mid.tiles.length - 54;
      expect(scatterApprox, `${id}: scatter ~${scatterApprox}, expected 3–14`).toBeLessThanOrEqual(14);
      expect(scatterApprox, `${id}: scatter ~${scatterApprox}, expected 3–14`).toBeGreaterThanOrEqual(3);
    }
  });

  it('every variant keeps the fire focal zone (cols 7–8, rows 1–2) clear of scatter', () => {
    // The fire + hearth own this zone — no props intrude so the blaze dominates.
    const SCATTER = new Set([
      'crate', 'crate_small', 'barrel', 'barrels_stacked', 'coffin', 'chest',
      'chair', 'plants', 'water', 'trapdoor_round', 'trapdoor_square',
      'stairs_down', 'weapon_longsword', 'weapon_bow', 'shield_curved', 'shield_straight',
      'track',
    ]);
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const mid = getMenuDioramaComposition(id).find((l) => l.id === 'mid')!;
      const intruders = mid.tiles.filter(
        (t) => SCATTER.has(t.frame) && t.col >= 7 && t.col <= 8 && t.row >= 1 && t.row <= 2,
      );
      expect(intruders, `${id}: scatter props intrude on the fire focal zone`).toEqual([]);
    }
  });

  it('every variant keeps the button UI stage (cols 6–9, rows 4–6) free of tall props', () => {
    // The menu buttons render over cols 6–9, rows 4–6. Tall props (crates,
    // coffins, barrels, chests) behind them hurt readability — only low-weight
    // floor textures (path/track/puddle/tiles_corner) may pass through.
    const TALL = new Set(['crate', 'crate_small', 'barrel', 'barrels_stacked', 'coffin', 'chest', 'chair']);
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const mid = getMenuDioramaComposition(id).find((l) => l.id === 'mid')!;
      const intruders = mid.tiles.filter(
        (t) => TALL.has(t.frame) && t.col >= 6 && t.col <= 9 && t.row >= 4 && t.row <= 6,
      );
      expect(intruders, `${id}: tall props behind the menu buttons`).toEqual([]);
    }
  });

  it('every variant keeps the warm tone unified — all warm fixtures forced to campfire-orange (tone 1)', () => {
    // Tone harmony: every warm fixture (any kind ≠ biome-glow) is forced to
    // TONE_WARM (campfire-orange) so the warm family never splits into a gold
    // 3rd tone. Crystals carry the variant hue (tone 2) — counts are per-variant
    // (EXPECTED_CRYSTALS); the warm/crystal COUNT split is no longer constant.
    const TONE_WARM_SIG = [1, 0.55, 0.22].map((v) => Number(v.toFixed(2))).join(',');
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const placements = getMenuDioramaPlacements(id);
      const warm = placements.filter((p) => p.kind !== 'biome-glow');
      const crystals = placements.filter((p) => p.kind === 'biome-glow');
      expect(warm.length + crystals.length, `${id}: warm+crystals must be the full rig`).toBe(
        placements.length,
      );
      expect(crystals, `${id}: crystal count drifted from the redesign rig`).toHaveLength(
        EXPECTED_CRYSTALS[id]!.count,
      );
      for (const p of warm) {
        const sig = p.color!.map((v) => Number(v.toFixed(2))).join(',');
        expect(sig, `${id}: warm fixture not unified to campfire-orange`).toBe(TONE_WARM_SIG);
      }
    }
  });

  it('each variant has a distinct frame-set vocabulary', () => {
    const signatures = new Map<string, Set<string>>();
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const composition = getMenuDioramaComposition(id);
      const frames = new Set<string>();
      for (const layer of composition) for (const t of layer.tiles) frames.add(t.frame);
      signatures.set(id, frames);
    }
    const sigJsons = new Set<string>();
    for (const [, frames] of signatures) {
      const sig = JSON.stringify([...frames].sort());
      expect(sigJsons.has(sig)).toBe(false);
      sigJsons.add(sig);
    }
  });

  it('NO light placement shares a tile with a cover/loot prop (no on-top stacking)', () => {
    // Regression guard for the "biome-glow on top of crates/coffins" complaint.
    // A light fixture (crystal / torch / candle / lantern / brazier / campfire)
    // must never render on top of a crate / coffin / barrel / chest — the
    // perimeter lights live in dedicated `LIGHT_NICHE` anchors that are disjoint
    // from the cover clusters + loot alcoves (see the coordinate budget docstring
    // in menuDioramaComposition.ts). Fractional placements (the central fire at
    // 7.5,1.5 — on the hearth) sit between tiles and are skipped (they render on
    // the hearth, never on a prop).
    const BLOCKING_FRAMES = new Set([
      'crate', 'crate_small', 'barrel', 'barrels_stacked', 'coffin', 'chest',
    ]);
    for (const id of MENU_DIORAMA_VARIANT_IDS) {
      const mid = getMenuDioramaComposition(id).find((l) => l.id === 'mid')!;
      const placements = getMenuDioramaPlacements(id);
      const blockingCells = new Set<string>();
      for (const t of mid.tiles) {
        if (BLOCKING_FRAMES.has(t.frame)) blockingCells.add(`${t.col},${t.row}`);
      }
      for (const p of placements) {
        if (!Number.isInteger(p.gridX) || !Number.isInteger(p.gridY)) continue;
        const key = `${p.gridX},${p.gridY}`;
        expect(
          blockingCells.has(key),
          `${id}: light '${p.kind}' at (${p.gridX},${p.gridY}) stacks on a cover/loot prop`,
        ).toBe(false);
      }
    }
  });
});
